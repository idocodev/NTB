// Writes supabase/seed.sql from src/lib/seed.ts. Run: node scripts/gen-seed.ts
import { writeFileSync } from 'node:fs'
import { SEED } from '../src/lib/seed.ts'

const q = (s: string | undefined) => (s == null ? 'null' : `'${s.replace(/'/g, "''")}'`)

const rows = SEED.map(
  (s, i) => `  (':LIST_KEY', ${q(s.name)}, ${q(s.quantity)}, ${q(s.category)}, now() - interval '${SEED.length - i} seconds', 'nano')`,
)

const sql = `-- The household list as it stood when the app was built (generated by scripts/gen-seed.ts).
-- Replace :LIST_KEY with the same value as VITE_LIST_KEY before running, e.g. in the Supabase SQL editor
-- find-and-replace ':LIST_KEY', or with psql: sed "s/:LIST_KEY/$VITE_LIST_KEY/" supabase/seed.sql | psql ...
-- added_by is left empty and source is 'nano': Nano kept this list before the app existed.

insert into public.items (list_key, name, quantity, category, created_at, source) values
${rows.join(',\n')};
`
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log(`wrote ${SEED.length} items`)
